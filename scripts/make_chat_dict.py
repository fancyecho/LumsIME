#!/usr/bin/env python3
"""Builds Support/rime/luma_chat.dict.yaml from Support/rime/luma_chat.txt.

rime-ice weighs words by how often they appear in written text, so everyday chat phrases sit at
its floor and lose abbreviations to written words (msd → 陌生的 before 马上到). Each phrase here
gets max(rime-ice's weight, a floor by length); build.sh lists this dictionary first, and for a
word in several tables rime keeps the first one's weight.

Needs pypinyin (pip install pypinyin). The generated file is committed, so building does not.
"""
import re, sys
from pathlib import Path
from pypinyin import lazy_pinyin

root = Path(__file__).resolve().parent.parent
FLOOR = {2: 150_000, 3: 200_000}  # 4+ characters use the 3-character floor

existing = {}
for table in (root / 'vendor/rime-ice/cn_dicts').glob('*.dict.yaml'):
    for line in table.read_text().splitlines():
        f = line.split('\t')
        if len(f) >= 3 and f[2].isdigit():
            existing[f[0]] = max(existing.get(f[0], 0), int(f[2]))

rows, seen = [], set()
for line in (root / 'Support/rime/luma_chat.txt').read_text().splitlines():
    line = line.split('#', 1)[0].strip()
    if not line:
        continue
    if '\t' in line:  # 词<Tab>拼 音: an explicit reading
        word, code = line.split('\t', 1)
        entries = [(word.strip(), code.strip())]
    else:
        entries = [(w, ' '.join(lazy_pinyin(w))) for w in line.split()]
    for word, code in entries:
        if word in seen or not re.fullmatch(r'[一-鿿]+', word):
            continue
        seen.add(word)
        weight = max(existing.get(word, 0), FLOOR[min(len(word), 3)])
        rows.append(f'{word}\t{code}\t{weight}')

out = root / 'Support/rime/luma_chat.dict.yaml'
out.write_text('# Generated by scripts/make_chat_dict.py from luma_chat.txt; edit that file instead.\n'
               '---\nname: luma_chat\nversion: "1"\nsort: by_weight\n...\n' + '\n'.join(rows) + '\n')
print(f'{len(rows)} phrases → {out}', file=sys.stderr)
