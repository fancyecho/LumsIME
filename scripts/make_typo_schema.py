#!/usr/bin/env python3
"""Generates luma_typo.schema.yaml: rime-ice's speller plus single-edit typo spellings.

    make_typo_schema.py <rime_ice.schema.yaml> <out.yaml>

The schema only exists to compile a second prism (luma_typo.prism.bin) over the rime_ice
dictionary. Its `luma_patch` block is applied to rime_ice by the build, adding a translator
that reads that prism and the lua filter that decides when a correction may win.
"""
import re
import sys

# Each typo spelling costs 0.5^STEPS of the word's weight (fuzz derivations chain their penalty).
STEPS = 2
QUALITY_OFFSET = 100  # keep in sync with OFFSET in lua/luma_typo.lua

source, out = sys.argv[1], sys.argv[2]
lines = open(source, encoding='utf-8').read().split('\n')


def scalar(key):
    for line in lines:
        m = re.match(rf'^  {key}:\s*(.*?)\s*(#.*)?$', line)
        if m:
            return m.group(1)
    raise SystemExit(f'{key} not found in {source}')


# rime-ice's own algebra: the list under `speller:` / `  algebra:`.
algebra, inside = [], False
for line in lines:
    if line == '  algebra:':
        inside = True
        continue
    if inside:
        if re.match(r'^    - ', line):
            algebra.append(re.sub(r'\s+#.*$', '', line.strip()[2:]).strip())
        elif line.strip() == '' or line.strip().startswith('#'):
            continue
        else:
            break
if not algebra:
    raise SystemExit('speller/algebra not found')

# Single-edit typos. Every edit tags its result with "~" so later rules can't stack on it
# (which would explode the prism), then the tag is stripped at the end.
SYL = r'(?=[a-z]*[aeiouv])'  # real syllables only, not abbreviations such as "zh"
edits = [
    rf'^{SYL}([zcs])h([a-z]+)$/$1$2~',          # zhi → zi
    rf'^{SYL}([zcs])([aeiou][a-z]*)$/$1h$2~',   # zi → zhi
    rf'^{SYL}([a-z]*[aei])ng$/$1n~',            # ang → an
    rf'^{SYL}([a-z]*[aei])n$/$1ng~',            # an → ang
]
edits += [rf'^{SYL}([a-z]{{{i}}})([a-z])([a-z])([a-z]*)$/$1$3$2$4~' for i in range(5)]  # swapped pair
edits += [rf'^{SYL}([a-z]{{{i}}})([a-z])([a-z]*)$/$1$2$2$3~' for i in range(6)]         # doubled key
edits += [rf'^{SYL}([a-z]{{{i}}})[a-z]([a-z]*)$/$1$2~' for i in range(1, 6)]            # dropped key
for row in ['qwertyuiop', 'asdfghjkl', 'zxcvbnm']:                                         # neighbouring key
    for j, c in enumerate(row):
        for n in [row[k] for k in (j - 1, j + 1) if 0 <= k < len(row)]:
            edits += [rf'^{SYL}([a-z]{{{i}}}){c}([a-z]*)$/$1{n}$2~' for i in range(6)]

typo = [f'derive/{e}/fuzz' for e in edits]
for j in range(2, STEPS + 1):
    typo.append(f'derive/^([a-z]+~{{{j - 1}}})$/$1~/fuzz')
    typo.append(f'erase/^[a-z]+~{{{j - 1}}}$/')
typo.append('xform/~+$//')


def q(s):
    return "'" + s.replace("'", "''") + "'"


# The main translator's initial_quality; the typo translator sits QUALITY_OFFSET below it.
block = lines[lines.index('translator:') + 1:]
block = block[:next(i for i, l in enumerate(block) if l and not l.startswith(' '))]
main_quality = next(float(re.match(r'^  initial_quality:\s*([\d.]+)', l).group(1))
                    for l in block if l.startswith('  initial_quality:'))
out_lines = [
    '# Generated by scripts/make_typo_schema.py from rime_ice.schema.yaml. Do not edit.',
    'schema:',
    '  schema_id: luma_typo',
    '  name: Luma 纠错',
    '  version: "1"',
    '  description: Typo-tolerant spellings for Luma. Not meant to be selected directly.',
    'speller:',
    f'  alphabet: {scalar("alphabet")}',
    f'  initials: {scalar("initials")}',
    '  delimiter: " \'"',
    '  algebra:',
    *[f'    - {q(r)}' for r in algebra + typo],
    'translator:',
    '  dictionary: rime_ice',
    '  prism: luma_typo',
    '',
    '# Applied to rime_ice by the build (see scripts/build.sh).',
    'luma_patch:',
    '  schema/dependencies/+: [luma_typo]',
    '  engine/translators/@after 1: script_translator@luma_typo',
    '  engine/filters/@before 0: lua_filter@*luma_typo',
    '  engine/filters/@next: lua_filter@*luma_kind  # tags assembled sentences for the app',
    '  translator/spelling_hints: 32  # the filter compares every candidate\'s pinyin with the input',
    '  luma_typo:',
    '    dictionary: rime_ice',
    '    prism: luma_typo',
    '    enable_user_dict: false',
    '    enable_word_completion: false',
    f'    initial_quality: {main_quality - QUALITY_OFFSET}',
    '    spelling_hints: 32',
    '    always_show_comments: true',
    '    comment_format:',
    "      - 'xform/^/［/'",
    "      - 'xform/$/］/'",
]
open(out, 'w', encoding='utf-8').write('\n'.join(out_lines) + '\n')
print(f'{out}: {len(algebra)} rime-ice rules + {len(typo)} typo rules')
